"""REPORT.md from outputs/. Every number comes from those files. Usage: python scripts/report.py"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def pct(x: float, digits: int = 1) -> str:
    return "n/a" if pd.isna(x) else f"{100 * x:.{digits}f}%"


def amount(x: float) -> str:
    return "n/a" if pd.isna(x) else (f"{x / 1e9:.2f} billion" if x >= 1e9 else f"{x / 1e6:.1f} million")


def table(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |\n| " + " | ".join("---" for _ in df.columns) + " |\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False))


def build(out: Path) -> str:
    snap = pd.read_csv(out / "snapshots.csv", parse_dates=["report_date"])
    comp = pd.read_csv(out / "compliance.csv")
    flows = pd.read_csv(out / "outflows.csv")
    ep = pd.read_csv(out / "episodes.csv")
    stress = pd.read_csv(out / "stress.csv")
    cross = pd.read_csv(out / "crosscheck.csv")
    rules = pd.read_csv(out / "rules.csv")
    params = json.loads((out / "parameters.json").read_text())
    latest = snap.sort_values("report_date").groupby("token").tail(1).set_index("token")
    u = latest.loc["USDC"]
    usdc = snap[snap.token == "USDC"]
    st_u = stress[(stress.token == "USDC") & (stress.scenario == "worst reference episode")].set_index(["horizon_days", "reading"])
    own_u = stress[(stress.token == "USDC") & (stress.scenario == "own worst")].set_index(["horizon_days", "reading"])
    fl = flows.set_index("token")
    thr = rules.set_index("rule").threshold
    daily_sig = pct(thr["Assets available within one working day, significant token"], 0)
    bank_cap = pct(thr["Deposits at one global or other systemically important institution"], 0)
    worst_ep = ep.loc[ep.groupby("horizon_days").outflow.idxmax()].set_index("horizon_days")

    lines = [
        "# What public disclosures say about e-money token reserves under MiCA",
        "",
        "Generated by `scripts/report.py` from `outputs/`. Method and limits: `METHOD.md`.",
        "",
        "## 1. Summary",
        "",
        (f"- USDC's published reserve on {u.report_date:%d %B %Y} held {pct(u.deposit_share)} in bank deposits and "
        f"{pct(u.fund_share)} in units of one US government money market fund, the Circle Reserve Fund. MiCA's "
        "rules bind the reserve of Circle's EU issuer, which is not published separately: the figures describe the "
        "global reserve, not the EU one."),
        (f"- Read through the fund, {pct(u.daily_share_look_through)} of that reserve is available within one working "
        f"day, far above the {daily_sig} of the draft rules for a significant token. Without the fund, whose units the EBA's "
        f"draft on eligible instruments does not admit, {pct(u.daily_share_strict)} is."),
        (f"- The largest one-day net outflow of the reference episodes ({worst_ep.loc[1, 'episode']}, "
        f"{pct(worst_ep.loc[1, 'outflow'])} of supply) is covered {st_u.loc[(1, 'look_through'), 'coverage']:.1f} times "
        f"by the one-day assets read through the fund, and {st_u.loc[(1, 'strict'), 'coverage']:.2f} times without "
        f"the fund. USDC's own worst day since it reached its present size, {pct(fl.loc['USDC', 'worst_1d'])} on "
        f"{fl.loc['USDC', 'worst_1d_date']}, is covered {own_u.loc[(1, 'strict'), 'coverage']:.1f} times even "
        "without the fund."),
        (f"- EURC, EURCV and USDCV are held in bank deposits and meet every rule on deposits and liquidity buckets. "
        f"SG-FORGE names its banks: EURCV is {pct(latest.loc['EURCV', 'largest_bank_share'])} at one bank and USDCV "
        f"{pct(latest.loc['USDCV', 'largest_bank_share'])}, above the {bank_cap} per-bank cap of the draft rules, which bind "
        "a non-significant token only if its supervisor requires them."),
        ("- Circle does not name its banks and nobody publishes deposit notice periods, so bank concentration, the "
        "risk behind USDC's loss of its peg in March 2023, cannot be checked from public data for USDC or EURC."),
        "",
        "## 2. Rules and their status",
        "",
        table(pd.DataFrame({"Rule": rules.rule, "Threshold": [f"{'at least' if o == '>=' else 'at most'} {pct(t, 0)}"
                                                               for o, t in zip(rules.op, rules.threshold)],
                            "Applies to": rules.applies_to, "Status": rules.status, "Source": rules.source})),
        "",
        "## 3. Reserves as published",
        "",
    ]
    lt = latest.reset_index()
    lines += [table(pd.DataFrame({
        "Token": lt.token, "Date": lt.report_date.dt.strftime("%Y-%m-%d"), "Circulation": lt.circulation.map(amount),
        "Reserve / circulation": lt.backing.map(lambda x: pct(x, 2)), "Bank deposits": lt.deposit_share.map(pct),
        "Fund units": lt.fund_share.map(pct), "Government securities": lt.sovereign_share.map(pct),
        "One day, through the fund": lt.daily_share_look_through.map(pct),
        "One day, without the fund": lt.daily_share_strict.map(pct),
        "Five days, through the fund": lt.weekly_share_look_through.map(pct),
        "Five days, without the fund": lt.weekly_share_strict.map(pct),
        "Largest bank": lt.largest_bank_share.map(pct)})), ""]
    lines += [("Government securities for EURQ and USDQ: Quantoz gives their share of the reserve but not their "
              "issuers or maturities, so they count in no liquidity bucket. SG-FORGE gives no reserve amount: its page "
              "states that the tokens are fully backed by cash, which the table takes at face value."), ""]

    lines += ["## 4. Rule by rule (latest snapshot)", ""]
    c = comp.copy()
    has_fund = c.token.map(latest.fund_share) > 0
    c = c[has_fund | (c.reading.fillna("") != "strict")].copy()
    c["reading"] = c.reading.fillna("").map({"look_through": "through the fund", "strict": "without the fund", "": ""})
    c.loc[c.token.map(latest.fund_share) == 0, "reading"] = ""
    lines += [table(pd.DataFrame({"Token": c.token, "Rule": c.rule, "Reading": c.reading, "Value": c.value.map(pct),
                                  "Threshold": [f"{o} {pct(t, 0)}" for o, t in zip(c.op, c.threshold)],
                                  "Status": c.status, "Result": c.result})), ""]
    lines += [f"USDC rows are computed on the {comp[comp.token == 'USDC'].scope.iloc[0]}.", ""]

    lines += ["## 5. USDC through 2026", ""]
    lines += [table(pd.DataFrame({
        "Date": usdc.report_date.dt.strftime("%Y-%m-%d"), "Circulation": usdc.circulation.map(amount),
        "Bank deposits": usdc.deposit_share.map(pct), "Fund units": usdc.fund_share.map(pct),
        "Bills held directly": usdc.sovereign_share_direct.map(pct),
        "One day, through the fund": usdc.daily_share_look_through.map(pct),
        "One day, without the fund": usdc.daily_share_strict.map(pct)})), ""]

    lines += ["## 6. Redemptions", "",
              ("Largest net outflows in each token's own history (days when its supply was at least a tenth of today's), "
              "from DefiLlama's daily circulating supply. Net outflows understate gross redemptions. Windows that contain "
              "a data change are left out, so a longer horizon can show a smaller figure."), ""]
    f = flows.copy()
    f["note"] = f.informative.map(lambda x: "" if x else "series flat on most days: not informative")
    lines += [table(pd.DataFrame({
        "Token": f.token, "Worst day": [f"{pct(v)} ({d})" for v, d in zip(f.worst_1d, f.worst_1d_date)],
        "Worst 7 days": [f"{pct(v)} ({d})" for v, d in zip(f.worst_7d, f.worst_7d_date)],
        "Worst 30 days": [f"{pct(v)} ({d})" for v, d in zip(f.worst_30d, f.worst_30d_date)],
        "99th percentile of a day": f.p99_1d.map(lambda x: pct(x, 2)), "Data changes left out": f.data_changes,
        "Note": f.note})), ""]
    lines += ["Reference episodes, same method:", ""]
    lines += [table(pd.DataFrame({"Episode": ep.episode, "Horizon": ep.horizon_days.map(lambda h: f"{h} days" if h > 1 else "1 day"),
                                  "Net outflow": ep.outflow.map(pct), "Ending": ep.date})), ""]

    lines += ["## 7. Stress", "",
              (f"Assets of the bucket divided by the stressed outflow. The gross variant multiplies the reference outflow by "
              f"{params['gross_over_net']:.2f}, the ratio of gross to net USDC redemptions on 13 March 2023. The last "
              "column is the share of bank deposits that could be frozen before the one-day assets fall short."), ""]
    s = stress[stress.token.isin(["USDC", "EURC", "EURCV"])].copy()
    s["reading"] = s.reading.map({"look_through": "through the fund", "strict": "without the fund"})
    s = s[~((s.token != "USDC") & (s.reading == "without the fund"))]
    s.loc[s.token != "USDC", "reading"] = ""
    lines += [table(pd.DataFrame({
        "Token": s.token, "Horizon": s.horizon_days.map(lambda h: "1 working day" if h == 1 else "5 working days"),
        "Scenario": s.scenario, "Reading": s.reading, "Outflow": s.outflow.map(pct), "Assets": s.liquid.map(pct),
        "Coverage": s.coverage.map(lambda x: "n/a" if pd.isna(x) else f"{x:.2f}"),
        "Deposits that can freeze": s.deposits_frozen_tolerated.map(pct)})), ""]

    lines += ["## 8. Checks", ""]
    for t, g in cross.groupby("token"):
        lines.append(f"- {t}: DefiLlama's supply against the attested circulation at Circle's {len(g)} report dates: "
                     f"median difference {pct(g.difference.median(), 2)}, largest {pct(g.difference.abs().max(), 2)}.")
    lines += [("- Every holding of Circle's reports is parsed and each printed subtotal and total equals the sum of "
              "its lines (`src/mrs/circle.py`)."), "",
              "## 9. Limits", "", "See `METHOD.md`, section on scope limits.", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "outputs")
    ap.add_argument("--report", type=Path, default=ROOT / "REPORT.md")
    args = ap.parse_args()
    args.report.write_text(build(args.out))


if __name__ == "__main__":
    main()
